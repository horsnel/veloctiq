// F10: Deepfake & Biometric Guard
// ============================================================================
export function deepfakeBiometricGuard(imageData: {
  data: Uint8ClampedArray;
  width: number;
  height: number;
}): FeatureResult {
  const { data, width, height } = imageData;
  const pixelCount = width * height;

  if (pixelCount === 0 || data.length < pixelCount * 4) {
    return {
      success: false,
      data: { error: 'Invalid image data' },
      source: 'browser',
      featureId: 'F10',
    };
  }

  // 1. Color banding analysis (deepfakes often have smooth gradient artifacts)
  const colorBandScore = analyzeColorBanding(data, width, height);

  // 2. Noise pattern analysis (deepfakes often have inconsistent noise)
  const noiseConsistency = analyzeNoiseConsistency(data, width, height);

  // 3. Edge consistency analysis
  const edgeConsistency = analyzeEdgeConsistency(data, width, height);

  // 4. Compression artifact analysis (double compression from generation)
  const compressionScore = analyzeCompressionArtifacts(data, width, height);

  // 5. Frequency domain analysis
  const frequencyAnomaly = analyzeFrequencyAnomalies(data, width, height);

  // Combined deepfake probability
  const deepfakeProbability = Math.min(
    colorBandScore * 0.2 +
    (1 - noiseConsistency) * 0.25 +
    (1 - edgeConsistency) * 0.2 +
    compressionScore * 0.15 +
    frequencyAnomaly * 0.2,
    1
  );

  const confidence = calculateDetectionConfidence([
    colorBandScore, 1 - noiseConsistency, 1 - edgeConsistency,
    compressionScore, frequencyAnomaly
  ]);

  const riskLevel =
    deepfakeProbability >= 0.7 ? 'high' :
    deepfakeProbability >= 0.4 ? 'medium' : 'low';

  return {
    success: true,
    data: {
      deepfakeProbability: Math.round(deepfakeProbability * 1000) / 1000,
      confidence: Math.round(confidence * 1000) / 1000,
      riskLevel,
      isLikelyDeepfake: deepfakeProbability >= 0.6,
      analysis: {
        colorBanding: Math.round(colorBandScore * 1000) / 1000,
        noiseConsistency: Math.round(noiseConsistency * 1000) / 1000,
        edgeConsistency: Math.round(edgeConsistency * 1000) / 1000,
        compressionArtifacts: Math.round(compressionScore * 1000) / 1000,
        frequencyAnomalies: Math.round(frequencyAnomaly * 1000) / 1000,
      },
      imageInfo: {
        width,
        height,
        pixelCount,
        bitsPerPixel: (data.length / pixelCount) * 8,
      },
      recommendation: deepfakeProbability >= 0.6
        ? 'This image exhibits characteristics consistent with AI-generated or manipulated content. Exercise caution.'
        : 'This image appears to be authentic based on pixel-level analysis.',
    },
    source: 'browser',
    featureId: 'F10',
  };
}

function analyzeColorBanding(data: Uint8ClampedArray, width: number, height: number): number {
  // Sample horizontal and vertical gradients for banding
  let bandingScore = 0;
  const sampleRows = Math.min(height, 50);
  const step = Math.floor(height / sampleRows);

  for (let y = 0; y < height; y += step) {
    let prevR = 0, prevG = 0, prevB = 0;
    let consecutiveSame = 0;
    let maxConsecutive = 0;

    for (let x = 1; x < width; x++) {
      const idx = (y * width + x) * 4;
      const r = data[idx];
      const g = data[idx + 1];
      const b = data[idx + 2];

      if (r === prevR && g === prevG && b === prevB) {
        consecutiveSame++;
        maxConsecutive = Math.max(maxConsecutive, consecutiveSame);
      } else {
        consecutiveSame = 0;
      }
      prevR = r;
      prevG = g;
      prevB = b;
    }

    if (maxConsecutive > width * 0.1) {
      bandingScore += 0.5;
    } else if (maxConsecutive > width * 0.05) {
      bandingScore += 0.2;
    }
  }

  return Math.min(bandingScore / Math.max(sampleRows, 1), 1);
}

function analyzeNoiseConsistency(data: Uint8ClampedArray, width: number, height: number): number {
  // Divide image into regions and compare noise levels
  const regions = 16;
  const regionWidth = Math.floor(width / Math.sqrt(regions));
  const regionHeight = Math.floor(height / Math.sqrt(regions));
  const noiseLevels: number[] = [];

  for (let ry = 0; ry < Math.floor(Math.sqrt(regions)); ry++) {
    for (let rx = 0; rx < Math.floor(Math.sqrt(regions)); rx++) {
      let noiseSum = 0;
      let noiseCount = 0;

      for (let y = ry * regionHeight + 1; y < (ry + 1) * regionHeight - 1 && y < height - 1; y++) {
        for (let x = rx * regionWidth + 1; x < (rx + 1) * regionWidth - 1 && x < width - 1; x++) {
          const idx = (y * width + x) * 4;
          const rightPixel = ((y * width + x + 1) * 4);
          (((y + 1) * width + x) * 4);

          for (let c = 0; c < 3; c++) {
            const diff = Math.abs(data[idx + c] - data[rightPixel + c]);
            noiseSum += diff;
            noiseCount++;
          }
        }
      }

      noiseLevels.push(noiseCount > 0 ? noiseSum / noiseCount : 0);
    }
  }

  if (noiseLevels.length < 2) return 0.5;

  const avgNoise = noiseLevels.reduce((a, b) => a + b, 0) / noiseLevels.length;
  const variance = noiseLevels.reduce((s, n) => s + Math.pow(n - avgNoise, 2), 0) / noiseLevels.length;
  const stdDev = Math.sqrt(variance);

  // High variance in noise = inconsistent = possible deepfake
  const consistency = 1 - Math.min(stdDev / Math.max(avgNoise, 1), 1);
  return Math.max(consistency, 0);
}

function analyzeEdgeConsistency(data: Uint8ClampedArray, width: number, height: number): number {
  // Check for smooth/blurry edges near sharp boundaries (common in deepfakes)
  let edgeScore = 0;
  let edgeCount = 0;

  for (let y = 1; y < height - 1; y += 4) {
    for (let x = 1; x < width - 1; x += 4) {
      const idx = (y * width + x) * 4;
      const right = (y * width + x + 1) * 4;
      const below = ((y + 1) * width + x) * 4;

      const gradient = Math.abs(data[idx] - data[right]) +
        Math.abs(data[idx] - data[below]) +
        Math.abs(data[idx + 1] - data[right + 1]) +
        Math.abs(data[idx + 1] - data[below + 1]);

      if (gradient > 100) {
        // Found a strong edge - check surroundings for blur
        let surroundingGradient = 0;
        let count = 0;
        for (let dy = -2; dy <= 2; dy++) {
          for (let dx = -2; dx <= 2; dx++) {
            const nx = x + dx;
            const ny = y + dy;
            if (nx > 0 && nx < width - 1 && ny > 0 && ny < height - 1) {
              const nIdx = (ny * width + nx) * 4;
              const nRight = (ny * width + nx + 1) * 4;
              surroundingGradient += Math.abs(data[nIdx] - data[nRight]);
              count++;
            }
          }
        }
        const avgSurrounding = surroundingGradient / Math.max(count, 1);
        // If edge is sharp but surroundings are smooth = potential boundary artifact
        if (avgSurrounding < gradient * 0.3) {
          edgeScore += 1;
        }
        edgeCount++;
      }
    }
  }

  return edgeCount > 0 ? Math.max(1 - (edgeScore / edgeCount), 0) : 0.8;
}

function analyzeCompressionArtifacts(data: Uint8ClampedArray, width: number, height: number): number {
  // Detect 8x8 block artifacts (JPEG double compression)
  let blockScore = 0;
  let blockCount = 0;

  for (let by = 0; by < height - 8; by += 8) {
    for (let bx = 0; bx < width - 8; bx += 8) {
      // Check corners of 8x8 blocks for discontinuities
      const topLeft = (by * width + bx) * 4;
      const topRight = (by * width + bx + 7) * 4;
      const bottomLeft = ((by + 7) * width + bx) * 4;
      const bottomRight = ((by + 7) * width + bx + 7) * 4;

      const crossDiff = Math.abs(data[topLeft] - data[bottomRight]) +
        Math.abs(data[topRight] - data[bottomLeft]);

      const centerIdx = ((by + 4) * width + bx + 4) * 4;
      const centerDiff = Math.abs(data[topLeft] - data[centerIdx]);

      if (crossDiff > centerDiff * 3 && crossDiff > 50) {
        blockScore += 1;
      }
      blockCount++;
    }
  }

  return blockCount > 0 ? Math.min(blockScore / blockCount * 5, 1) : 0;
}

function analyzeFrequencyAnomalies(data: Uint8ClampedArray, width: number, height: number): number {
  // Check for unusual high-frequency or low-frequency content
  let highFreq = 0;
  let lowFreq = 0;
  let totalSamples = 0;

  for (let y = 1; y < height - 1; y += 2) {
    for (let x = 1; x < width - 1; x += 2) {
      const idx = (y * width + x) * 4;
      const right = (y * width + x + 1) * 4;
      ((y + 1) * width + x) * 4;

      const dx = Math.abs(data[idx] - data[right]);

      if (dx > 30) highFreq++;
      if (dx < 3) lowFreq++;
      totalSamples++;
    }
  }

  if (totalSamples === 0) return 0;

  const highFreqRatio = highFreq / totalSamples;
  const lowFreqRatio = lowFreq / totalSamples;

  // Too much high freq = over-sharpened (deepfake), too much low = over-smoothed
  const anomalyScore = Math.abs(highFreqRatio - 0.15) + Math.abs(lowFreqRatio - 0.5);
  return Math.min(anomalyScore * 2, 1);
}

function calculateDetectionConfidence(scores: number[]): number {
  // Confidence based on agreement between different analysis methods
  const avg = scores.reduce((a, b) => a + b, 0) / scores.length;
  const variance = scores.reduce((s, v) => s + Math.pow(v - avg, 2), 0) / scores.length;
  const agreement = 1 - Math.min(Math.sqrt(variance) / Math.max(avg, 0.1), 1);
  return Math.max(agreement, 0.2);
}

