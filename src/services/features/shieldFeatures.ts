export function toxicityThresholdSlider(
  text: string,
  threshold: number = 0.5
): FeatureResult {
  const lower = text.toLowerCase();
  const words = lower.split(/\s+/).filter(w => w.length > 0);
  const totalWords = Math.max(words.length, 1);

  // Word-based toxicity scoring
  let toxicWordScore = 0;
  const matchedToxicWords: string[] = [];
  const toxicCategories: Record<string, number> = {
    profanity: 0,
    hate_speech: 0,
    violence: 0,
    insult: 0,
    sexual: 0,
  };

  const hateSpeechWords = ['hate', 'racist', 'racism', 'sexist', 'bigot', 'nazi', 'nigger', 'faggot', 'spic', 'chink', 'kike', 'homophobe'];
  const violenceWords = ['kill', 'die', 'murder', 'rape', 'bomb', 'shoot', 'attack', 'violent', 'drown', 'burn', 'choke', 'strangle', 'smash', 'destroy'];
  const insultWords = ['stupid', 'idiot', 'dumb', 'ugly', 'trash', 'garbage', 'worthless', 'useless', 'pathetic', 'loser', 'moron', 'clown', 'joke', 'cringe', 'lame', 'delusional'];
  const sexualWords = ['fuck', 'rape', 'molest', 'pedophile', 'dick', 'cock', 'pussy', 'slut', 'whore', 'anal', 'penis', 'vagina'];

  for (const word of words) {
    const cleanWord = word.replace(/[^a-z]/g, '');
    if (TOXICITY_WORD_LIST.includes(cleanWord)) {
      toxicWordScore += 1;
      matchedToxicWords.push(cleanWord);
      if (hateSpeechWords.includes(cleanWord)) toxicCategories.hate_speech += 1;
      if (violenceWords.includes(cleanWord)) toxicCategories.violence += 1;
      if (insultWords.includes(cleanWord)) toxicCategories.insult += 1;
      if (sexualWords.includes(cleanWord)) toxicCategories.sexual += 1;
    }
  }

  toxicCategories.profanity =
    toxicWordScore - toxicCategories.hate_speech - toxicCategories.violence - toxicCategories.insult - toxicCategories.sexual;

  // Normalize to 0-1
  const wordToxicity = Math.min(toxicWordScore / (totalWords * 0.3), 1);

  // Caps ratio
  const capsRatio = (text.match(/[A-Z]/g) || []).length / Math.max(text.replace(/\s/g, '').length, 1);
  const capsToxicity = capsRatio > 0.6 ? Math.min((capsRatio - 0.6) * 2, 0.4) : 0;

  // Exclamation / punctuation intensity
  const exclamationCount = (text.match(/[!]{2,}/g) || []).length;
  const questionMarkCount = (text.match(/\?{2,}/g) || []).length;
  const punctuationIntensity = Math.min((exclamationCount + questionMarkCount) * 0.08, 0.2);

  // Repetition detection (same word repeated 3+ times)
  const wordFrequencies: Record<string, number> = {};
  for (const w of words) {
    wordFrequencies[w] = (wordFrequencies[w] || 0) + 1;
  }
  const repeatedWords = Object.entries(wordFrequencies).filter(([, count]) => count >= 3);
  const repetitionToxicity = Math.min(repeatedWords.length * 0.1, 0.3);

  // Toxic emoji analysis
  let toxicEmojiCount = 0;
  for (const pattern of TOXIC_EMOJI_PATTERNS) {
    const matches = text.match(pattern);
    if (matches) toxicEmojiCount += matches.length;
  }
  const emojiToxicity = Math.min(toxicEmojiCount * 0.1, 0.2);

  // Combined toxicity score
  const rawScore =
    wordToxicity * 0.45 +
    capsToxicity * 0.15 +
    punctuationIntensity * 0.1 +
    repetitionToxicity * 0.15 +
    emojiToxicity * 0.15;

  const toxicityScore = Math.min(Math.max(rawScore, 0), 1);
  const normalizedScore = Math.round(toxicityScore * 1000) / 1000;

  // Determine filter recommendation
  const shouldFilter = normalizedScore >= threshold;
  const primaryCategories = Object.entries(toxicCategories)
    .filter(([, count]) => count > 0)
    .sort(([, a], [, b]) => b - a)
    .map(([cat]) => cat);

  return {
    success: true,
    data: {
      text: text.slice(0, 200),
      toxicityScore: normalizedScore,
      isToxic: normalizedScore >= threshold,
      threshold,
      shouldFilter,
      filterRecommendation: shouldFilter
        ? `Content exceeds toxicity threshold of ${threshold}. Score: ${normalizedScore.toFixed(2)}`
        : 'Content is within acceptable toxicity range',
      categories: primaryCategories,
      categoryScores: toxicCategories,
      matchedToxicWords: [...new Set(matchedToxicWords)],
      analysis: {
        wordToxicity: Math.round(wordToxicity * 1000) / 1000,
        capsToxicity: Math.round(capsToxicity * 1000) / 1000,
        punctuationIntensity: Math.round(punctuationIntensity * 1000) / 1000,
        repetitionToxicity: Math.round(repetitionToxicity * 1000) / 1000,
        emojiToxicity: Math.round(emojiToxicity * 1000) / 1000,
        capsRatio: Math.round(capsRatio * 100) / 100,
        exclamationCount,
        repeatedWords: repeatedWords.map(([w, c]) => ({ word: w, count: c })),
        toxicEmojiCount,
      },
      wordCount: totalWords,
    },
    source: 'browser',
    featureId: 'F3',
  };
}

// ============================================================================
// F4: Shadow-Ban Early Warning
// ============================================================================
export function shadowBanEarlyWarning(metrics: {
  followerCount: number;
  recentPostImpressions: number[];
  recentPostLikes: number[];
  recentPostComments: number[];
  recentPostShares: number[];
  postsPerWeek: number;
  accountAgeDays: number;
  platform: string;
}): FeatureResult {
  const {
    followerCount,
    recentPostImpressions,
    recentPostLikes,
    recentPostComments,
    recentPostShares,
    postsPerWeek,
    accountAgeDays,
    platform,
  } = metrics;

  const postCount = recentPostImpressions.length;
  if (postCount === 0) {
    return {
      success: false,
      data: { error: 'No post data provided' },
      source: 'browser',
      featureId: 'F4',
    };
  }

  // 1. Reach Ratio Analysis (impressions / followers)
  const reachRatios = recentPostImpressions.map(
    imp => followerCount > 0 ? imp / followerCount : 0
  );
  const avgReachRatio = reachRatios.reduce((a, b) => a + b, 0) / postCount;
  const expectedReachRatio = platform === 'instagram' ? 0.12 :
    platform === 'tiktok' ? 0.15 :
    platform === 'twitter' ? 0.05 :
    platform === 'youtube' ? 0.08 : 0.1;
  const reachRatioAnomaly = avgReachRatio < expectedReachRatio * 0.3;

  // 2. Engagement Velocity (trend of engagement over recent posts)
  const engagementRates = recentPostImpressions.map((imp, i) => {
    const totalEngagement =
      (recentPostLikes[i] || 0) +
      (recentPostComments[i] || 0) +
      (recentPostShares[i] || 0);
    return imp > 0 ? totalEngagement / imp : 0;
  });

  // Calculate engagement trend (linear regression slope)
  let sumX = 0, sumY = 0, sumXY = 0, sumX2 = 0;
  for (let i = 0; i < engagementRates.length; i++) {
    sumX += i;
    sumY += engagementRates[i];
    sumXY += i * engagementRates[i];
    sumX2 += i * i;
  }
  const n = engagementRates.length;
  const engagementSlope = n > 1
    ? (n * sumXY - sumX * sumY) / (n * sumX2 - sumX * sumX)
    : 0;
  const engagementDeclining = engagementSlope < -0.001;

  // 3. Content Visibility Score
  const avgImpressions = recentPostImpressions.reduce((a, b) => a + b, 0) / postCount;
  const impressionVariance = recentPostImpressions.reduce(
    (sum, imp) => sum + Math.pow(imp - avgImpressions, 2), 0
  ) / postCount;
  Math.sqrt(impressionVariance);
  const visibilityScore = Math.min(avgReachRatio / expectedReachRatio, 1);

  // 4. Engagement consistency check
  const avgEngagement = engagementRates.reduce((a, b) => a + b, 0) / n;
  const engVariance = engagementRates.reduce(
    (sum, eng) => sum + Math.pow(eng - avgEngagement, 2), 0
  ) / n;
  const engagementStdDev = Math.sqrt(engVariance);
  const engagementConsistency = avgEngagement > 0 ? 1 - (engagementStdDev / avgEngagement) : 0;

  // 5. Hashtag reach test (proxy: if posts have similar content but very different reach)
  const reachDropOff = reachRatios.length > 3
    ? reachRatios.slice(-3).reduce((a, b) => a + b, 0) / 3
    : avgReachRatio;
  const earlierReach = reachRatios.length > 6
    ? reachRatios.slice(0, 3).reduce((a, b) => a + b, 0) / 3
    : avgReachRatio;
  const reachDeclineRatio = earlierReach > 0 ? reachDropOff / earlierReach : 1;

  // 6. Account age factor (new accounts with high posting but low reach = suspicious)
  const accountMaturity = Math.min(accountAgeDays / 365, 1);
  const postingIntensity = postsPerWeek / 7;
  const anomalousNewAccount = accountMaturity < 0.3 && postingIntensity > 2 && avgReachRatio < expectedReachRatio * 0.2;

  // Compile risk factors
  const riskFactors: { factor: string; value: number; risk: boolean; description: string }[] = [];
  riskFactors.push({
    factor: 'Reach Ratio',
    value: Math.round(avgReachRatio * 1000) / 1000,
    risk: reachRatioAnomaly,
    description: `Average reach ratio is ${(avgReachRatio * 100).toFixed(1)}% vs expected ${(expectedReachRatio * 100).toFixed(1)}%`,
  });
  riskFactors.push({
    factor: 'Engagement Trend',
    value: Math.round(engagementSlope * 10000) / 10000,
    risk: engagementDeclining,
    description: engagementDeclining
      ? `Engagement declining at rate ${engagementSlope.toFixed(5)} per post`
      : 'Engagement trend is stable or improving',
  });
  riskFactors.push({
    factor: 'Content Visibility',
    value: Math.round(visibilityScore * 1000) / 1000,
    risk: visibilityScore < 0.3,
    description: `Visibility score is ${(visibilityScore * 100).toFixed(1)}%`,
  });
  riskFactors.push({
    factor: 'Engagement Consistency',
    value: Math.round(engagementConsistency * 1000) / 1000,
    risk: engagementConsistency < 0.3,
    description: `Engagement consistency is ${(engagementConsistency * 100).toFixed(1)}%`,
  });
  riskFactors.push({
    factor: 'Reach Decline',
    value: Math.round(reachDeclineRatio * 1000) / 1000,
    risk: reachDeclineRatio < 0.5,
    description: `Recent reach is ${(reachDeclineRatio * 100).toFixed(1)}% of earlier reach`,
  });
  riskFactors.push({
    factor: 'Account Anomaly',
    value: anomalousNewAccount ? 1 : 0,
    risk: anomalousNewAccount,
    description: anomalousNewAccount
      ? 'New account with high posting frequency but suspiciously low reach'
      : 'Account age and activity patterns are normal',
  });

  const activeRiskFactors = riskFactors.filter(f => f.risk).length;
  const shadowBanRiskScore = Math.min(
    (activeRiskFactors / riskFactors.length) * 0.6 +
    (reachRatioAnomaly ? 0.2 : 0) +
    (engagementDeclining ? 0.2 : 0),
    1
  );

  const riskLevel =
    shadowBanRiskScore >= 0.7 ? 'high' :
    shadowBanRiskScore >= 0.4 ? 'medium' : 'low';

  return {
    success: true,
    data: {
      shadowBanRiskScore: Math.round(shadowBanRiskScore * 1000) / 1000,
      riskLevel,
      isShadowBanned: shadowBanRiskScore >= 0.7,
      platform,
      riskFactors,
      summary: {
        avgReachRatio: Math.round(avgReachRatio * 1000) / 1000,
        expectedReachRatio,
        engagementSlope: Math.round(engagementSlope * 10000) / 10000,
        visibilityScore: Math.round(visibilityScore * 1000) / 1000,
        reachDeclineRatio: Math.round(reachDeclineRatio * 1000) / 1000,
        postsAnalyzed: postCount,
      },
      recommendations: riskLevel === 'high'
        ? [
            'Immediately review recent posts for guideline violations',
            'Check if posts appear in hashtag search results',
            'Test with a secondary account to verify visibility',
            'Review recent activity for behavior that may trigger spam filters',
            'Consider reducing posting frequency temporarily',
          ]
        : riskLevel === 'medium'
        ? [
            'Monitor reach and engagement trends closely over the next week',
            'Avoid using banned or shadow-banned hashtags',
            'Ensure content follows platform community guidelines',
            'Space out posts to avoid trigger patterns',
          ]
        : [
            'Account appears to be in good standing',
            'Continue monitoring reach metrics weekly',
          ],
    },
    source: 'browser',
    featureId: 'F4',
  };
}

// ============================================================================
// F5: Narrative Hijack Alert
// ============================================================================
export function narrativeHijackAlert(comments: {
  text: string;
  timestamp?: string;
  username?: string;
}[]): FeatureResult {
  if (comments.length < 3) {
    return {
      success: true,
      data: {
        hijackDetected: false,
        analysis: 'Insufficient comments for reliable analysis',
        commentsNeeded: 3,
      },
      source: 'browser',
      featureId: 'F5',
    };
  }

  // Sentiment word lists
  const positiveWords = new Set([
    'good', 'great', 'amazing', 'love', 'best', 'awesome', 'excellent',
    'fantastic', 'perfect', 'beautiful', 'wonderful', 'incredible',
    'brilliant', 'outstanding', 'superb', 'enjoy', 'happy', 'nice',
    'agree', 'thanks', 'thank', 'appreciate', 'well', 'nice', 'cool',
    'fire', 'lit', 'slay', 'goated', 'w', 'based', 'facts', 'real',
  ]);
  const negativeWords = new Set([
    'bad', 'terrible', 'hate', 'worst', 'awful', 'horrible',
    'disgusting', 'pathetic', 'useless', 'boring', 'waste',
    'disappointing', 'poor', 'wrong', 'fail', 'cringe', 'trash',
    'garbage', 'biased', 'lie', 'lies', 'fake', 'propaganda',
    'manipulation', 'brainwash', 'narrative', 'agenda', 'shill',
  ]);

  // Analyze each comment sentiment
  const sentiments = comments.map(comment => {
    const words = comment.text.toLowerCase().split(/\s+/);
    let pos = 0, neg = 0;
    for (const w of words) {
      const clean = w.replace(/[^a-z']/g, '');
      if (positiveWords.has(clean)) pos++;
      if (negativeWords.has(clean)) neg++;
    }
    return {
      sentiment: pos - neg,
      pos,
      neg,
      total: Math.max(words.length, 1),
    };
  });

  // Split comments into segments for temporal analysis
  const segmentSize = Math.max(Math.floor(comments.length / 3), 2);
  const segments: { start: number; end: number; avgSentiment: number; count: number }[] = [];
  for (let i = 0; i < comments.length; i += segmentSize) {
    const seg = sentiments.slice(i, i + segmentSize);
    const avg = seg.reduce((s, v) => s + v.sentiment, 0) / Math.max(seg.length, 1);
    segments.push({ start: i, end: i + seg.length, avgSentiment: avg, count: seg.length });
  }

  // Detect narrative shift (significant sentiment change between segments)
  let narrativeShiftDetected = false;
  let shiftMagnitude = 0;
  const shifts: { from: number; to: number; magnitude: number }[] = [];

  for (let i = 1; i < segments.length; i++) {
    const diff = Math.abs(segments[i].avgSentiment - segments[i - 1].avgSentiment);
    shifts.push({
      from: segments[i - 1].avgSentiment,
      to: segments[i].avgSentiment,
      magnitude: diff,
    });
    if (diff > 1.5) {
      narrativeShiftDetected = true;
      shiftMagnitude = Math.max(shiftMagnitude, diff);
    }
  }

  // Astroturfing detection: check for suspiciously similar comments
  const normalizedComments = comments.map(c =>
    c.text.toLowerCase().replace(/[^\w\s]/g, '').trim()
  );
  const nGrams: Record<string, number> = {};
  const nGramSize = 3;

  for (const comment of normalizedComments) {
    const words = comment.split(/\s+/);
    for (let i = 0; i <= words.length - nGramSize; i++) {
      const gram = words.slice(i, i + nGramSize).join(' ');
      if (gram.length > 10) {
        nGrams[gram] = (nGrams[gram] || 0) + 1;
      }
    }
  }

  // Find repeated n-grams (potential coordinated messaging)
  const repeatedNGrams = Object.entries(nGrams)
    .filter(([, count]) => count >= 2)
    .sort(([, a], [, b]) => b - a)
    .slice(0, 10);

  const astroturfingScore = Math.min(repeatedNGrams.length * 0.15, 0.8);
  const isAstroturfing = astroturfingScore > 0.3;

  // Comment similarity cluster detection
  const similarityThreshold = 0.6;
  const clusters: string[][] = [];
  const assigned = new Set<number>();

  for (let i = 0; i < normalizedComments.length; i++) {
    if (assigned.has(i)) continue;
    const cluster: string[] = [comments[i].text];
    assigned.add(i);

    for (let j = i + 1; j < normalizedComments.length; j++) {
      if (assigned.has(j)) continue;
      const similarity = computeJaccardSimilarity(
        new Set(normalizedComments[i].split(/\s+/)),
        new Set(normalizedComments[j].split(/\s+/))
      );
      if (similarity >= similarityThreshold) {
        cluster.push(comments[j].text);
        assigned.add(j);
      }
    }

    if (cluster.length >= 2) {
      clusters.push(cluster);
    }
  }

  // Coordinated activity signals
  const userCommentCounts: Record<string, number> = {};
  for (const c of comments) {
    if (c.username) {
      userCommentCounts[c.username] = (userCommentCounts[c.username] || 0) + 1;
    }
  }
  const suspiciousUsers = Object.entries(userCommentCounts)
    .filter(([, count]) => count >= 3)
    .map(([user, count]) => ({ user, count }))
    .sort((a, b) => b.count - a.count);

  const hijackScore = Math.min(
    (narrativeShiftDetected ? 0.35 : 0) +
    astroturfingScore * 0.35 +
    (clusters.length > 0 ? 0.15 : 0) +
    (suspiciousUsers.length > 0 ? 0.15 : 0),
    1
  );

  const hijackLevel =
    hijackScore >= 0.6 ? 'high' :
    hijackScore >= 0.3 ? 'medium' : 'low';

  return {
    success: true,
    data: {
      hijackScore: Math.round(hijackScore * 1000) / 1000,
      hijackLevel,
      hijackDetected: hijackScore >= 0.3,
      narrativeShiftDetected,
      narrativeShiftMagnitude: Math.round(shiftMagnitude * 100) / 100,
      segments,
      shifts: shifts.filter(s => s.magnitude > 0.5),
      astroturfing: {
        detected: isAstroturfing,
        score: Math.round(astroturfingScore * 1000) / 1000,
        repeatedPhrases: repeatedNGrams.map(([phrase, count]) => ({ phrase, count })),
      },
      similarityClusters: clusters.map((cluster, i) => ({
        clusterId: i + 1,
        commentCount: cluster.length,
        sampleComment: cluster[0].slice(0, 100),
      })),
      suspiciousUsers,
      recommendations: hijackLevel === 'high'
        ? [
            'Multiple coordinated activity signals detected',
            'Consider restricting comments temporarily',
            'Review repeated phrases for copy-paste campaigns',
            'Flag suspicious users for review',
          ]
        : hijackLevel === 'medium'
        ? [
            'Monitor for escalating coordinated activity',
            'Review users posting multiple similar comments',
          ]
        : [
            'Comment thread appears organic',
            'Continue standard monitoring',
          ],
    },
    source: 'browser',
    featureId: 'F5',
  };
}

function computeJaccardSimilarity(setA: Set<string>, setB: Set<string>): number {
  const intersection = new Set([...setA].filter(x => setB.has(x)));
  const union = new Set([...setA, ...setB]);
  return union.size > 0 ? intersection.size / union.size : 0;
}

// ============================================================================
// F6: Ghost Function (Bot Pattern Generator & Detector)
// ============================================================================
export function ghostFunction(
  mode: 'generate' | 'detect',
  input: { count: number; username?: string; profileData?: Record<string, any> }
): FeatureResult {
  if (mode === 'generate') {
    const { count } = input;
    const patterns: Record<string, any>[] = [];

    for (let i = 0; i < count; i++) {
      // Generate bot-like username patterns
      const generators = [
        () => {
          const words = ['digital', 'tech', 'social', 'media', 'growth', 'marketing', 'brand', 'content', 'crypto', 'trade'];
          const word = words[Math.floor(Math.random() * words.length)];
          const digits = String(Math.floor(Math.random() * 9999) + 1000);
          return `${word}_${digits}`;
        },
        () => {
          const adjectives = ['super', 'mega', 'ultra', 'pro', 'real', 'best', 'top', 'the'];
          const nouns = ['user', 'fan', 'lover', 'follower', 'person', 'guy', 'girl', 'one'];
          return `${adjectives[Math.floor(Math.random() * adjectives.length)]}${nouns[Math.floor(Math.random() * nouns.length)]}${Math.floor(Math.random() * 999) + 1}`;
        },
        () => {
          const chars = 'abcdefghijklmnopqrstuvwxyz0123456789';
          let result = '';
          for (let j = 0; j < 12; j++) {
            result += chars.charAt(Math.floor(Math.random() * chars.length));
          }
          return result;
        },
      ];

      const username = generators[Math.floor(Math.random() * generators.length)]();

      // Generate bot behavioral patterns
      const postingFrequency = Math.random() > 0.5
        ? 'high_frequency' // Many posts per day
        : 'burst_pattern'; // Occasional bursts

      const engagementStyle = Math.random() > 0.5
        ? 'generic_positive' // "Great post!", "Amazing!"
        : 'self_promotional'; // "Follow me back!", links

      const timing = Math.random() > 0.5
        ? 'regular_intervals' // Posts at exact same times
        : 'irregular_bursts'; // Sporadic posting

      patterns.push({
        username,
        fingerprint: {
          postingFrequency,
          engagementStyle,
          timing,
          entropy: Math.round((3 + Math.random() * 2) * 100) / 100,
          patternType: 'synthetic',
        },
        detectionResistance: [
          'humanized_username',
          'varied_comment_length',
          'emoji_usage',
          'natural_timing_jitter',
        ],
      });
    }

    return {
      success: true,
      data: {
        patterns,
        count: patterns.length,
        usage: 'Use these patterns to test your bot detection systems',
      },
      source: 'browser',
      featureId: 'F6',
    };
  }

  // Detect mode
  const { username = '', profileData } = input;
  let deceptionScore = 0;
  const indicators: string[] = [];

  // Check for bot-deception techniques
  // Humanization indicators (too perfect to be real)
  const bio = profileData?.bio || '';
  const bioLength = bio.length;

  // Perfect bio with all elements = suspicious
  const hasEmoji = /[\u{1F300}-\u{1F9FF}]/gu.test(bio);
  const hasLink = /https?:\/\//i.test(bio);
  const hasCallToAction = /follow|like|subscribe|check out/i.test(bio);
  const hasEmail = /@/.test(bio);

  const bioCompleteness = [hasEmoji, hasLink, hasCallToAction, hasEmail].filter(Boolean).length;
  if (bioCompleteness >= 3 && bioLength < 150) {
    deceptionScore += 0.3;
    indicators.push('overly_optimized_bio');
  }

  // Follower/following ratio analysis
  const followers = profileData?.followers || 0;
  const following = profileData?.following || 0;
  if (followers > 0 && following > 0) {
    const ratio = followers / following;
    if (ratio > 10) {
      deceptionScore += 0.15;
      indicators.push('celebrity_ratio_suspicious');
    } else if (ratio < 0.1 && followers < 100) {
      deceptionScore += 0.2;
      indicators.push('low_follower_high_following');
    }
  }

  // Post timing regularity
  const postTimestamps = profileData?.postTimestamps as number[] || [];
  if (postTimestamps.length >= 5) {
    const intervals: number[] = [];
    for (let i = 1; i < postTimestamps.length; i++) {
      intervals.push(postTimestamps[i] - postTimestamps[i - 1]);
    }
    const avgInterval = intervals.reduce((a, b) => a + b, 0) / intervals.length;
    const variance = intervals.reduce((s, v) => s + Math.pow(v - avgInterval, 2), 0) / intervals.length;
    const coefficientOfVariation = Math.sqrt(variance) / Math.max(avgInterval, 1);

    // Too regular = bot-like. Too irregular but with repeating patterns = bot with jitter
    if (coefficientOfVariation < 0.1) {
      deceptionScore += 0.25;
      indicators.push('machine_like_posting_regular');
    }
  }

  // Comment pattern analysis
  const recentComments = profileData?.recentComments as string[] || [];
  if (recentComments.length >= 3) {
    const commentLengths = recentComments.map(c => c.length);
    const avgLen = commentLengths.reduce((a, b) => a + b, 0) / commentLengths.length;
    const lenVariance = commentLengths.reduce((s, l) => s + Math.pow(l - avgLen, 2), 0) / commentLengths.length;
    const lenStdDev = Math.sqrt(lenVariance);

    // Very uniform comment lengths = suspicious
    if (lenStdDev < 5 && avgLen > 10) {
      deceptionScore += 0.2;
      indicators.push('uniform_comment_lengths');
    }

    // Generic comment patterns
    const genericPhrases = ['great post', 'love this', 'amazing content', 'nice one', 'keep it up', 'awesome', 'wow', 'so true', 'exactly', 'facts'];
    const genericCount = recentComments.filter(c =>
      genericPhrases.some(p => c.toLowerCase().includes(p))
    ).length;
    if (genericCount / recentComments.length > 0.6) {
      deceptionScore += 0.2;
      indicators.push('high_generic_comment_ratio');
    }
  }

  // Fingerprint anomaly: account creation to first activity ratio
  if (profileData?.createdAt && postTimestamps.length > 0) {
    const age = Date.now() - new Date(profileData.createdAt).getTime();
    const firstPost = Math.min(...postTimestamps);
    const timeToFirstPost = firstPost - new Date(profileData.createdAt).getTime();
    if (age > 0 && timeToFirstPost > 0) {
      const activityRatio = timeToFirstPost / age;
      // Immediate posting after creation = bot signal
      if (activityRatio < 0.01) {
        deceptionScore += 0.15;
        indicators.push('instant_activity_after_creation');
      }
    }
  }

  deceptionScore = Math.min(deceptionScore, 1);
  const isUsingDeception = deceptionScore > 0.5;

  return {
    success: true,
    data: {
      username,
      deceptionScore: Math.round(deceptionScore * 1000) / 1000,
      isUsingDeception,
      confidence: deceptionScore > 0.7 ? 'high' : deceptionScore > 0.4 ? 'medium' : 'low',
      indicators,
      recommendation: isUsingDeception
        ? 'Account exhibits bot-deception techniques. Recommend manual review.'
        : 'Account behavior appears authentic',
    },
    source: 'browser',
    featureId: 'F6',
  };
}

// ============================================================================
// F7: IP Leak Protection
// ============================================================================
export function ipLeakProtection(): FeatureResult {
  const privacyChecks: { name: string; status: 'protected' | 'vulnerable' | 'unknown'; description: string }[] = [];
  let privacyScore = 1.0;

  // 1. WebRTC Detection
  const hasRTCPeerConnection = typeof (window as any).RTCPeerConnection !== 'undefined' ||
    typeof (window as any).mozRTCPeerConnection !== 'undefined' ||
    typeof (window as any).webkitRTCPeerConnection !== 'undefined';

  if (hasRTCPeerConnection) {
    privacyChecks.push({
      name: 'WebRTC',
      status: 'vulnerable',
      description: 'WebRTC is available. WebRTC can leak local IP addresses even when using a VPN. Consider disabling or using a WebRTC blocking extension.',
    });
    privacyScore -= 0.25;
  } else {
    privacyChecks.push({
      name: 'WebRTC',
      status: 'protected',
      description: 'WebRTC is not available or has been disabled.',
    });
  }

  // 2. Browser Fingerprint Uniqueness Scoring
  const canvas = document.createElement('canvas');
  const ctx = canvas.getContext('2d');
  let canvasFingerprint = '';
  if (ctx) {
    ctx.textBaseline = 'top';
    ctx.font = '14px Arial';
    ctx.fillStyle = '#f60';
    ctx.fillRect(125, 1, 62, 20);
    ctx.fillStyle = '#069';
    ctx.fillText('VelocTiq.Fingerprint', 2, 15);
    ctx.fillStyle = 'rgba(102, 204, 0, 0.7)';
    ctx.fillText('VelocTiq.Fingerprint', 4, 17);
    canvasFingerprint = canvas.toDataURL().slice(-50);
  }

  const fingerprintSignals: string[] = [];
  const userAgent = navigator.userAgent;
  const language = navigator.language;
  const languages = navigator.languages ? navigator.languages.join(',') : language;
  const platform = navigator.platform;
  const hardwareConcurrency = navigator.hardwareConcurrency || 0;
  const deviceMemory = (navigator as any).deviceMemory || 0;
  const screenResolution = `${screen.width}x${screen.height}`;
  const colorDepth = screen.colorDepth;
  const timezone = Intl.DateTimeFormat().resolvedOptions().timeZone;
  const touchSupport = 'ontouchstart' in window ? 'touch' : 'no-touch';
  const maxTouchPoints = navigator.maxTouchPoints || 0;

  fingerprintSignals.push(`UA: ${userAgent.slice(0, 40)}`);
  fingerprintSignals.push(`Lang: ${language}`);
  fingerprintSignals.push(`Platform: ${platform}`);
  fingerprintSignals.push(`Screen: ${screenResolution}`);
  fingerprintSignals.push(`Timezone: ${timezone}`);
  fingerprintSignals.push(`Touch: ${touchSupport}(${maxTouchPoints})`);

  // Calculate fingerprint uniqueness
  let fingerprintUniqueness = 0.5; // base uniqueness

  // Rare screen resolution
  const commonResolutions = ['1920x1080', '1366x768', '1536x864', '1440x900', '1280x720'];
  if (!commonResolutions.includes(screenResolution)) fingerprintUniqueness += 0.1;

  // Multiple languages
  if (navigator.languages && navigator.languages.length > 2) fingerprintUniqueness += 0.1;

  // High hardware concurrency
  if (hardwareConcurrency > 8) fingerprintUniqueness += 0.05;

  // Do Not Track
  const dnt = navigator.doNotTrack;
  if (dnt === '1') {
    privacyChecks.push({
      name: 'Do Not Track',
      status: 'protected',
      description: 'Do Not Track header is enabled.',
    });
    privacyScore += 0.05;
  } else {
    privacyChecks.push({
      name: 'Do Not Track',
      status: 'vulnerable',
      description: 'Do Not Track is not enabled. Enable it in browser settings for additional privacy.',
    });
  }

  // Canvas fingerprint protection
  if (canvasFingerprint.length > 0) {
    privacyChecks.push({
      name: 'Canvas Fingerprint',
      status: 'vulnerable',
      description: 'Canvas fingerprinting is possible. This allows trackers to identify your browser uniquely.',
    });
    privacyScore -= 0.1;
  }

  // Cookie check
  const cookiesEnabled = navigator.cookieEnabled;
  if (cookiesEnabled) {
    privacyChecks.push({
      name: 'Cookies',
      status: 'vulnerable',
      description: 'Cookies are enabled. Third-party cookies can track your browsing activity.',
    });
    privacyScore -= 0.05;
  } else {
    privacyChecks.push({
      name: 'Cookies',
      status: 'protected',
      description: 'Cookies are disabled.',
    });
  }

  // 3. DNS Leak Pattern Detection (heuristic)
  const isUsingProxy = /vpn|proxy|tor/i.test(userAgent);
  if (!isUsingProxy) {
    privacyChecks.push({
      name: 'VPN/Proxy Detection',
      status: 'vulnerable',
      description: 'No VPN or proxy indicator detected in user agent. Consider using a VPN for additional privacy.',
    });
    privacyScore -= 0.15;
  }

  fingerprintUniqueness = Math.min(fingerprintUniqueness, 1);
  privacyScore = Math.max(Math.min(privacyScore, 1), 0);

  const recommendations: string[] = [];
  if (privacyScore < 0.5) recommendations.push('Critical: Multiple privacy vulnerabilities detected');
  if (hasRTCPeerConnection) recommendations.push('Install a WebRTC leak protection extension');
  if (cookiesEnabled) recommendations.push('Block third-party cookies in browser settings');
  if (!isUsingProxy) recommendations.push('Consider using a reputable VPN service');
  if (canvasFingerprint.length > 0) recommendations.push('Use a canvas fingerprint randomizer extension');
  if (dnt !== '1') recommendations.push('Enable Do Not Track in browser settings');
  if (recommendations.length === 0) recommendations.push('Your browser privacy posture is strong');

  return {
    success: true,
    data: {
      privacyScore: Math.round(privacyScore * 1000) / 1000,
      privacyGrade: privacyScore >= 0.8 ? 'A' : privacyScore >= 0.6 ? 'B' : privacyScore >= 0.4 ? 'C' : 'D',
      checks: privacyChecks,
      fingerprintAnalysis: {
        uniqueness: Math.round(fingerprintUniqueness * 1000) / 1000,
        signals: fingerprintSignals,
        canvasHash: canvasFingerprint ? canvasFingerprint.slice(0, 20) + '...' : 'unavailable',
      },
      browserInfo: {
        userAgent: userAgent.slice(0, 80),
        language,
        languages,
        platform,
        hardwareConcurrency,
        deviceMemory,
        screenResolution,
        colorDepth,
        timezone,
        touchSupport,
        maxTouchPoints,
        cookiesEnabled,
        doNotTrack: dnt,
      },
      recommendations,
    },
    source: 'browser',
    featureId: 'F7',
  };
}

