// F15: Prompt Injection Shield 2.0 (Advanced)
// ============================================================================
export function promptInjectionShield(
  text: string,
  context?: { conversationHistory?: string[]; systemPromptHash?: string }
): FeatureResult {
  const detections: { type: string; layer: string; severity: number; description: string; match: string }[] = [];
  let overallSeverity = 0;

  // === LAYER 1: Direct Pattern Matching ===
  const directPatterns = [
    { pattern: /ignore\s+(all\s+)?previous\s+(instructions?|prompts?|rules?|context)/i, type: 'instruction_override', severity: 0.95 },
    { pattern: /system\s*(prompt|message|instruction)/i, type: 'system_prompt_access', severity: 0.9 },
    { pattern: /<\|?(system|im_start|endoftext)\|?>/i, type: 'special_token_injection', severity: 0.95 },
    { pattern: /\<system\>|\<\/system\>/i, type: 'xml_injection', severity: 0.9 },
    { pattern: /return\s+(the|your|full|complete)\s+(prompt|instructions?|system)/i, type: 'data_extraction', severity: 0.95 },
    { pattern: /print\s+(your|the|all)\s+(instructions?|rules?|prompt)/i, type: 'data_extraction', severity: 0.9 },
    { pattern: /reveal\s+(your|the|hidden)\s+(prompt|instructions?)/i, type: 'data_extraction', severity: 0.9 },
    { pattern: /you\s+are\s+now\s+(a|an|the)\s+/i, type: 'role_play', severity: 0.7 },
    { pattern: /pretend\s+(you\s+are|that\s+you|to\s+be)/i, type: 'role_play', severity: 0.7 },
    { pattern: /act\s+as\s+(if|a|an|the)\s+/i, type: 'role_play', severity: 0.7 },
    { pattern: /forget\s+(everything|all|your)\s+(previous|past|training)/i, type: 'memory_wipe', severity: 0.85 },
    { pattern: /disregard\s+(your|all|previous|the)\s+(instructions?|rules?)/i, type: 'instruction_override', severity: 0.9 },
    { pattern: /override\s+(your|the|all)\s+(instructions?|rules?|guidelines?)/i, type: 'instruction_override', severity: 0.95 },
    { pattern: /from\s+now\s+on[,\s]/i, type: 'context_switch', severity: 0.6 },
    { pattern: /new\s+(set\s+of\s+)?(instructions?|rules?|guidelines?)/i, type: 'rule_replacement', severity: 0.8 },
    { pattern: /repeat\s+(the|your|back)\s+(prompt|instructions?|above)/i, type: 'data_extraction', severity: 0.9 },
    { pattern: /translate\s+(the|your)\s+(instructions?|prompt)\s+into/i, type: 'data_extraction', severity: 0.85 },
    { pattern: /summarize\s+(your|the)\s+(instructions?|prompt|rules)/i, type: 'data_extraction', severity: 0.85 },
    { pattern: /what\s+(are|is)\s+your\s+(instructions?|rules?|guidelines?)/i, type: 'data_extraction', severity: 0.7 },
  ];

  for (const { pattern, type, severity } of directPatterns) {
    const match = text.match(pattern);
    if (match) {
      detections.push({
        type,
        layer: 'direct_pattern',
        severity,
        description: `Direct ${type} pattern detected`,
        match: match[0].slice(0, 80),
      });
      overallSeverity = Math.max(overallSeverity, severity);
    }
  }

  // === LAYER 2: Encoded Injection Detection ===
  // Base64 encoded injection attempts
  const base64Pattern = /(?:[A-Za-z0-9+/]{40,}={0,2})/g;
  const base64Matches = text.match(base64Pattern) || [];
  for (const encoded of base64Matches) {
    try {
      const decoded = atob(encoded);
      // Check if decoded content contains injection patterns
      if (/ignore|system|prompt|instruction|override/i.test(decoded)) {
        detections.push({
          type: 'base64_injection',
          layer: 'encoded',
          severity: 0.9,
          description: `Base64 encoded injection attempt: "${decoded.slice(0, 50)}"`,
          match: encoded.slice(0, 40) + '...',
        });
        overallSeverity = Math.max(overallSeverity, 0.9);
      }
    } catch {
      // Not valid base64, skip
    }
  }

  // Hex encoded injection attempts
  const hexPattern = /(?:0x[0-9a-fA-F]{4,})+/g;
  const hexMatches = text.match(hexPattern) || [];
  for (const hex of hexMatches) {
    try {
      const decoded = hex.replace(/0x/g, '').match(/.{2}/g)?.map(h => String.fromCharCode(parseInt(h, 16))).join('') || '';
      if (/ignore|system|prompt/i.test(decoded)) {
        detections.push({
          type: 'hex_injection',
          layer: 'encoded',
          severity: 0.85,
          description: `Hex encoded injection attempt`,
          match: hex.slice(0, 40),
        });
        overallSeverity = Math.max(overallSeverity, 0.85);
      }
    } catch {
      // Not valid hex, skip
    }
  }

  // === LAYER 3: Unicode-based Attacks ===
  // Zero-width characters
  const zeroWidthChars = /[\u200B\u200C\u200D\u200E\u200F\uFEFF]/g;
  const zwMatches = text.match(zeroWidthChars) || [];
  if (zwMatches.length > 0) {
    detections.push({
      type: 'zero_width_injection',
      layer: 'unicode',
      severity: 0.75,
      description: `Zero-width characters detected (${zwMatches.length} instances). May contain hidden instructions.`,
      match: `${zwMatches.length} zero-width characters`,
    });
    overallSeverity = Math.max(overallSeverity, 0.75);
  }

  // Unicode confusable characters (homoglyphs)
  const confusablePatterns = [
    { char: /\u0410/g, desc: 'Cyrillic А (looks like Latin A)' },
    { char: /\u0412/g, desc: 'Cyrillic В (looks like Latin B)' },
    { char: /\u0415/g, desc: 'Cyrillic Е (looks like Latin E)' },
    { char: /\u041A/g, desc: 'Cyrillic К (looks like Latin K)' },
    { char: /\u041E/g, desc: 'Cyrillic О (looks like Latin O)' },
    { char: /\u0420/g, desc: 'Cyrillic Р (looks like Latin P)' },
    { char: /\u0421/g, desc: 'Cyrillic С (looks like Latin C)' },
    { char: /\u0425/g, desc: 'Cyrillic Х (looks like Latin X)' },
    { char: /\u0423/g, desc: 'Cyrillic У (looks like Latin Y)' },
  ];

  let confusableCount = 0;
  const foundConfusables: string[] = [];
  for (const { char, desc } of confusablePatterns) {
    if (char.test(text)) {
      confusableCount++;
      foundConfusables.push(desc);
    }
  }
  if (confusableCount > 2) {
    detections.push({
      type: 'unicode_confusable',
      layer: 'unicode',
      severity: 0.7,
      description: `Multiple unicode confusable characters detected: ${foundConfusables.slice(0, 3).join(', ')}`,
      match: `${confusableCount} confusable characters`,
    });
    overallSeverity = Math.max(overallSeverity, 0.7);
  }

  // RTL override attacks
  if (/[\u202E\u202A\u202B\u202C\u202D]/g.test(text)) {
    detections.push({
      type: 'rtl_override',
      layer: 'unicode',
      severity: 0.8,
      description: 'Right-to-left override characters detected. May be used to hide malicious text.',
      match: 'RTL override characters',
    });
    overallSeverity = Math.max(overallSeverity, 0.8);
  }

  // === LAYER 4: Multi-turn Injection Patterns ===
  if (context?.conversationHistory && context.conversationHistory.length > 2) {
    // Check if conversation gradually escalates injection attempts
    const recentTurns = context.conversationHistory.slice(-5);
    let injectionEscalation = 0;
    for (const turn of recentTurns) {
      const turnLower = turn.toLowerCase();
      if (/ignore|override|pretend|act as|system/i.test(turnLower)) {
        injectionEscalation++;
      }
    }
    if (injectionEscalation >= 3) {
      detections.push({
        type: 'multi_turn_escalation',
        layer: 'conversation',
        severity: 0.85,
        description: `Escalating injection attempts across ${injectionEscalation} recent conversation turns`,
        match: `${injectionEscalation} turns with injection patterns`,
      });
      overallSeverity = Math.max(overallSeverity, 0.85);
    }

    // Context drift detection (conversation steering)
    const firstTurn = context.conversationHistory[0].toLowerCase();
    const lastTurn = context.conversationHistory[context.conversationHistory.length - 1].toLowerCase();
    const firstWords = new Set(firstTurn.split(/\s+/).slice(0, 5));
    const lastWords = new Set(lastTurn.split(/\s+/).slice(0, 5));
    const topicOverlap = [...firstWords].filter(w => lastWords.has(w)).length;
    const topicDrift = 1 - (topicOverlap / Math.max(firstWords.size, 1));

    if (topicDrift > 0.8 && context.conversationHistory.length > 5) {
      detections.push({
        type: 'topic_drift_attack',
        layer: 'conversation',
        severity: 0.65,
        description: 'Significant topic drift detected across conversation. May indicate steering attack.',
        match: `Topic drift: ${(topicDrift * 100).toFixed(0)}%`,
      });
      overallSeverity = Math.max(overallSeverity, 0.65);
    }
  }

  // === LAYER 5: Obfuscation Detection ===
  // Split injection (instructions broken across lines/words)
  const suspiciousLineBreaks = (text.match(/\n\s*\n\s*\n/g) || []).length;
  if (suspiciousLineBreaks >= 3) {
    detections.push({
      type: 'formatting_obfuscation',
      layer: 'obfuscation',
      severity: 0.4,
      description: 'Excessive line breaks may be used to obfuscate injection text',
      match: `${suspiciousLineBreaks} instances of triple+ line breaks`,
    });
    overallSeverity = Math.max(overallSeverity, 0.4);
  }

  // Mixed case/special char injection
  const mixedCaseWords = text.split(/\s+/).filter(w =>
    /[a-z]/.test(w) && /[A-Z]/.test(w) && w.length > 10
  );
  if (mixedCaseWords.length > 3) {
    detections.push({
      type: 'case_obfuscation',
      layer: 'obfuscation',
      severity: 0.35,
      description: 'Multiple words with mixed casing may indicate obfuscated injection',
      match: `${mixedCaseWords.length} mixed-case words`,
    });
    overallSeverity = Math.max(overallSeverity, 0.35);
  }

  // === SANITIZED OUTPUT ===
  let sanitizedText = text;
  for (const { type, match } of detections) {
    if (type !== 'zero_width_injection' && type !== 'unicode_confusable') {
      sanitizedText = sanitizedText.replace(match, '[BLOCKED]');
    }
  }
  // Remove zero-width characters
  sanitizedText = sanitizedText.replace(/[\u200B\u200C\u200D\u200E\u200F\uFEFF\u202E\u202A\u202B\u202C\u202D]/g, '');

  const threatLevel =
    overallSeverity >= 0.85 ? 'critical' :
    overallSeverity >= 0.7 ? 'high' :
    overallSeverity >= 0.4 ? 'medium' : 'low';

  return {
    success: true,
    data: {
      sanitizedText: sanitizedText.slice(0, 300),
      isThreat: overallSeverity >= 0.7,
      threatLevel,
      threatScore: Math.round(overallSeverity * 1000) / 1000,
      layers: {
        direct_pattern: detections.filter(d => d.layer === 'direct_pattern').length,
        encoded: detections.filter(d => d.layer === 'encoded').length,
        unicode: detections.filter(d => d.layer === 'unicode').length,
        conversation: detections.filter(d => d.layer === 'conversation').length,
        obfuscation: detections.filter(d => d.layer === 'obfuscation').length,
      },
      detections: detections.sort((a, b) => b.severity - a.severity),
      recommendation: threatLevel === 'critical'
        ? 'CRITICAL: Advanced multi-layer injection detected. Use sanitized text only.'
        : threatLevel === 'high'
        ? 'HIGH: Sophisticated injection attempt detected. Review sanitized output.'
        : threatLevel === 'medium'
        ? 'MEDIUM: Potential obfuscation detected. Monitor for escalation.'
        : 'LOW: No significant injection threats detected.',
    },
    source: 'browser',
    featureId: 'F15',
  };
}

