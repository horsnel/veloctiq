// ============================================================================
// F1: Behavioral Bot Identification
// ============================================================================
export function behavioralBotIdentification(
  usernames: string[]
): FeatureResult {
  const results = usernames.map((username) => {
    const lower = username.toLowerCase().replace(/[^a-z0-9_.]/g, '');
    let botProbability = 0;
    const flags: string[] = [];
    const signals: Record<string, number> = {};

    // --- Username Pattern Analysis ---
    // Numeric suffix (4+ trailing digits)
    const numericSuffix = lower.match(/(\d+)$/);
    if (numericSuffix) {
      const digits = numericSuffix[1].length;
      if (digits >= 4) {
        botProbability += 0.25;
        flags.push('numeric_suffix_long');
        signals.numericSuffix = digits;
      } else if (digits >= 2) {
        botProbability += 0.1;
        flags.push('numeric_suffix_short');
      }
    }

    // Prefix + underscore + number pattern (name_123)
    if (/^[a-z]+_\d+$/.test(lower)) {
      botProbability += 0.2;
      flags.push('name_number_pattern');
    }

    // Suspicious keywords in username
    const suspiciousKeywords = [
      'bot', 'auto', 'spam', 'fake', 'follow', 'free', 'hack',
      'gain', 'real', 'official', 'verified', 'promo', 'deals',
      'click', 'win', 'cash', 'crypto', 'nft', 'airdrop',
      'elonsmusk', 'muskbaby', 'givelike', 'likemore',
    ];
    for (const kw of suspiciousKeywords) {
      if (lower.includes(kw)) {
        botProbability += 0.15;
        flags.push(`keyword_${kw}`);
        break; // only flag once
      }
    }

    // Excessive length
    if (lower.length > 20) {
      botProbability += 0.1;
      flags.push('excessive_length');
    }
    if (lower.length > 30) {
      botProbability += 0.1;
      flags.push('very_long_username');
    }

    // Very short random-looking strings (8+ hex chars)
    if (/^[a-z0-9]{8,}$/.test(lower)) {
      // Calculate Shannon entropy
      const freq: Record<string, number> = {};
      for (const c of lower) freq[c] = (freq[c] || 0) + 1;
      const len = lower.length;
      let entropy = 0;
      for (const c in freq) {
        const p = freq[c] / len;
        entropy -= p * Math.log2(p);
      }
      if (entropy > 3.5) {
        botProbability += 0.3;
        flags.push('high_entropy_random');
        signals.entropy = Math.round(entropy * 100) / 100;
      }
    }

    // Repeated characters (aaabbb, xxx)
    const consecutiveRepeats = (lower.match(/(.)\1{2,}/g) || []).length;
    if (consecutiveRepeats >= 2) {
      botProbability += 0.2;
      flags.push('repeated_chars');
      signals.repeats = consecutiveRepeats;
    }

    // No vowels (pure consonant strings suggest gibberish)
    const hasVowel = /[aeiou]/.test(lower);
    if (!hasVowel && lower.length > 5) {
      botProbability += 0.15;
      flags.push('no_vowels');
    }

    // All-caps-like pattern after replace (many consecutive uppercase in original)
    if (username === username.toUpperCase() && username.length > 3 && /[a-z]/i.test(username)) {
      botProbability += 0.1;
      flags.push('all_uppercase');
    }

    // Starts with common bot prefixes
    const botPrefixes = ['the_', 'mr_', 'ms_', 'dr_', 'im_', 'i_am_', 'its_'];
    for (const prefix of botPrefixes) {
      if (lower.startsWith(prefix) && lower.length < 15) {
        botProbability += 0.05;
        break;
      }
    }

    // Contains multiple underscores
    const underscoreCount = (lower.match(/_/g) || []).length;
    if (underscoreCount >= 3) {
      botProbability += 0.1;
      flags.push('multiple_underscores');
    }

    // --- Behavioral Signal Heuristics ---
    // Name looks auto-generated (word + random digits)
    if (/^[a-z]{3,8}\d{4,8}$/.test(lower)) {
      botProbability += 0.2;
      flags.push('autogenerated_pattern');
    }

    // Mix of common words with random digits
    const commonNameWords = ['user', 'admin', 'new', 'test', 'temp', 'just', 'cool', 'best', 'good', 'love'];
    const hasCommonPrefix = commonNameWords.some(w => lower.startsWith(w));
    const endsWithDigits = /^\d+$/.test(lower.split('_').pop() || '');
    if (hasCommonPrefix && endsWithDigits) {
      botProbability += 0.15;
      flags.push('common_prefix_random_suffix');
    }

    // Clamp and determine confidence
    botProbability = Math.min(botProbability, 1);
    const confidence =
      botProbability > 0.7 ? 'high' :
      botProbability > 0.4 ? 'medium' : 'low';

    const isBot = botProbability > 0.55;

    return {
      username,
      botProbability: Math.round(botProbability * 1000) / 1000,
      isBot,
      confidence,
      flags,
      signals,
      recommendation: isBot
        ? 'Quarantine and review for automated behavior'
        : botProbability > 0.3
        ? 'Monitor for suspicious activity'
        : 'Likely human account',
    };
  });

  const summary = {
    totalAnalyzed: results.length,
    botsDetected: results.filter(r => r.isBot).length,
    highConfidence: results.filter(r => r.confidence === 'high').length,
    averageBotProbability:
      Math.round(
        (results.reduce((s, r) => s + r.botProbability, 0) / Math.max(results.length, 1)) * 1000
      ) / 1000,
  };

  return {
    success: true,
    data: { results, summary },
    source: 'browser',
    featureId: 'F1',
  };
}

